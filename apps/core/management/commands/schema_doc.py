"""Spec 16 §11.1: write docs/schema.md (the data dictionary) and docs/erd.mmd (Mermaid) from the models.
`--check` exits 1 when the committed files differ (CI)."""
import sys
from pathlib import Path

from django.apps import apps
from django.conf import settings
from django.core.management.base import BaseCommand
from django.db import models

from apps.core.schema_policy import JSON_REASONS, check_model, expected

DOMAINS = [
    ("Identity and access", ["accounts", "access", "audit"]),
    ("Candidates", ["candidates", "follows"]),
    ("Money", ["donations"]),
    ("Party and voter", ["membership", "pvc"]),
    ("Content", ["news", "posts"]),
    ("Moderation", ["moderation"]),
    ("Notifications", ["notifications"]),
    ("Privacy and security", ["privacy"]),
    ("Geography", ["geo"]),
    ("Search and platform", ["search", "core", "integrations", "media"]),
]


def _ours():
    return sorted((m for m in apps.get_models() if m.__module__.startswith("apps.")), key=lambda m: m._meta.label)


def _register():
    from apps.privacy import register

    cats = {}
    for c in register.CATEGORIES:
        for label in c.models:
            cats[label] = c.label
    for label in register.NOT_PERSONAL:
        cats.setdefault(label, "Not personal")
    return cats


def _type(f):
    name = type(f).__name__
    if isinstance(f, models.CharField):
        return f"varchar({f.max_length})"
    return {"UUIDField": "uuid", "DateTimeField": "timestamptz", "DateField": "date", "BooleanField": "boolean", "TextField": "text",
            "JSONField": "jsonb", "BigIntegerField": "bigint", "IntegerField": "integer", "PositiveIntegerField": "integer ≥ 0",
            "PositiveSmallIntegerField": "smallint ≥ 0", "BigAutoField": "bigint (auto)", "BinaryField": "bytea",
            "GenericIPAddressField": "inet", "SearchVectorField": "tsvector", "ForeignKey": "→", "OneToOneField": "→ (one)",
            "URLField": "varchar (url)", "EmailField": "varchar (email)", "SlugField": "varchar (slug)"}.get(name, name)


def _cell(s):
    return str(s).replace("|", "/").replace("\n", " ")


def _q(q):
    if isinstance(q, tuple):
        k, v = q
        v = getattr(v, "value", v)
        if k.endswith("__isnull"):
            return f"{k[:-8]} is {'null' if v else 'not null'}"
        if k.endswith("__in"):
            vals = [str(getattr(x, "value", x)) for x in v]
            return f"{k[:-4]} in ({', '.join(vals) if len(vals) <= 10 else f'{len(vals)} values'})"
        if "__" in k:
            field, op = k.rsplit("__", 1)
            return f"{field} {dict(gte='≥', lte='≤', gt='>', lt='<').get(op, op)} {v}"
        return f"{k} = {v!r}" if isinstance(v, str) else f"{k} = {v}"
    if not isinstance(q, models.Q):
        return str(q)
    parts = [_q(c) for c in q.children]
    text = f" {q.connector.lower()} ".join(f"({p})" if len(parts) > 1 and (" and " in p or " or " in p) else p for p in parts)
    return f"not ({text})" if q.negated else text


def _constraint_text(c):
    if isinstance(c, models.UniqueConstraint):
        cond = f" where {_q(c.condition)}" if c.condition is not None else ""
        return f"unique ({', '.join(c.fields)}){cond}"
    if isinstance(c, models.CheckConstraint):
        return f"check {_q(c.condition)}"
    return type(c).__name__


def build_markdown():
    cats = _register()
    labels = {m._meta.label: m for m in _ours()}
    out = ["# NDCConnect data dictionary", "",
           "Generated by `python manage.py schema_doc` from the models (spec 16 §11.1). Do not edit by hand; CI fails when it drifts.",
           "Conventions and the delete-rule policy: `context/feature-specs/16-database-schema.md` §3 and §5.", ""]
    for domain, app_labels in DOMAINS:
        ms = [m for m in labels.values() if m._meta.app_label in app_labels]
        if not ms:
            continue
        out += [f"## {domain}", ""]
        for m in sorted(ms, key=lambda m: m._meta.label):
            o = m._meta
            out += [f"### `{o.label}` — `{o.db_table}`", "", " ".join((m.__doc__ or "").split()), "",
                    f"Data register: {cats.get(o.label, '—')}.", "",
                    "| Column | Type | Null | Notes |", "|---|---|---|---|"]
            for f in o.concrete_fields:
                notes = []
                if f.primary_key:
                    notes.append("primary key")
                if f.is_relation:
                    allowed, why = expected(f)
                    notes.append(f"→ `{f.related_model._meta.label}`, on delete {f.remote_field.on_delete.__name__} ({why})")
                if getattr(f, "unique", False) and not f.primary_key:
                    notes.append("unique")
                if f.choices and not f.is_relation:
                    vals = [str(v) for v, _ in f.choices]
                    notes.append("one of " + (", ".join(vals) if len(vals) <= 10 else f"{len(vals)} values"))
                if isinstance(f, models.JSONField):
                    notes.append(JSON_REASONS.get(f"{o.label}.{f.name}", ""))
                if f.db_index and not f.is_relation and not f.unique and not f.primary_key:
                    notes.append("indexed")
                out.append(f"| `{f.column}` | {_type(f)} | {'yes' if f.null else ''} | {_cell('; '.join(n for n in notes if n))} |")
            if o.constraints:
                out += ["", "Constraints:", ""] + [f"- `{c.name}`: {_cell(_constraint_text(c))}" for c in o.constraints]
            if o.indexes:
                out += ["", "Indexes:", ""] + [f"- `{i.name}`: ({', '.join(i.fields)})" + (f" where {_q(i.condition)}" if i.condition is not None else "")
                                                for i in o.indexes]
            out.append("")
    return "\n".join(out).rstrip() + "\n"


def build_mermaid():
    out = ["%% NDCConnect entity relationships. Generated by `python manage.py schema_doc` (spec 16 §11.1).", "erDiagram"]
    for m in _ours():
        for f in m._meta.concrete_fields:
            if not f.is_relation or f.related_model is None or not f.related_model.__module__.startswith("apps."):
                continue
            if f.related_model._meta.label == "accounts.User" and f.remote_field.on_delete is models.SET_NULL:
                continue  # actor links would bury the diagram; they're in schema.md
            a, b = f.related_model.__name__, m.__name__
            left = "||" if not f.null else "|o"
            right = "o|" if getattr(f, "one_to_one", False) else "o{"
            out.append(f'  {a} {left}--{right} {b} : "{f.name}"')
    return "\n".join(out) + "\n"


class Command(BaseCommand):
    help = "Write docs/schema.md and docs/erd.mmd from the models (spec 16 §11.1). --check fails on drift or policy problems."

    def add_arguments(self, parser):
        parser.add_argument("--check", action="store_true")

    def handle(self, *args, check=False, **opts):
        docs = Path(settings.BASE_DIR) / "docs"
        files = {docs / "schema.md": build_markdown(), docs / "erd.mmd": build_mermaid()}
        problems = [p for m in _ours() for p in check_model(m)]
        if check:
            stale = [p.name for p, text in files.items() if not p.exists() or p.read_text() != text]
            for p in problems:
                self.stderr.write(p)
            if stale:
                self.stderr.write(f"Stale: {', '.join(stale)}. Run `python manage.py schema_doc`.")
            if stale or problems:
                sys.exit(1)
            self.stdout.write("Schema docs are current.")
            return
        for p, text in files.items():
            p.write_text(text)
        for p in problems:
            self.stderr.write(p)
        self.stdout.write(f"Wrote {', '.join(p.name for p in files)}" + (f"; {len(problems)} policy problems" if problems else ""))
